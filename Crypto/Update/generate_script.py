"""
Generate a PowerShell script to run update_prices.py for all configured folders.
Reads folder list from config.py and generates run_updates.ps1
"""

import sys
from pathlib import Path

# Get the directory where this script is located
SCRIPT_DIR = Path(__file__).parent

# Import config
sys.path.insert(0, str(SCRIPT_DIR))
try:
    from config import FOLDERS
except ImportError:
    print("Error: Could not import config.py")
    sys.exit(1)


def generate_powershell_script():
    """Generate PowerShell script to run all update_prices.py files."""
    
    if not FOLDERS:
        print("Warning: No folders configured in config.py")
        return
    
    # Get the project root (parent of Crypto folder)
    crypto_dir = SCRIPT_DIR.parent
    project_root = crypto_dir.parent
    
    script_content = []
    script_content.append("# Auto-generated PowerShell script to run update_prices.py for all configured folders")
    script_content.append("# Generated by generate_script.py")
    script_content.append("#")
    script_content.append("")
    script_content.append(f"$projectRoot = \"{project_root}\"")
    script_content.append("")
    script_content.append("Write-Host \"Running update_prices.py for all configured folders...\"")
    script_content.append("Write-Host \"=\" * 60")
    script_content.append("")
    
    for folder in FOLDERS:
        folder_path = crypto_dir / folder
        script_content.append(f"# {folder}")
        script_content.append(f"$folder = \"{folder_path}\"")
        script_content.append("if (Test-Path $folder) {")
        script_content.append("    $updateScript = Join-Path $folder \"update_prices.py\"")
        script_content.append("    if (Test-Path $updateScript) {")
        script_content.append("        Write-Host \"\"")
        script_content.append("        Write-Host \"=\" * 60")
        script_content.append(f"        Write-Host \"Running update_prices.py in: {folder}\"")
        script_content.append("        Write-Host \"=\" * 60")
        script_content.append("        Push-Location $folder")
        script_content.append("        python update_prices.py")
        script_content.append("        if ($LASTEXITCODE -ne 0) {")
        script_content.append("            Write-Host \"[FAILED] Exit code: $LASTEXITCODE\" -ForegroundColor Red")
        script_content.append("        } else {")
        script_content.append("            Write-Host \"[SUCCESS] Completed\" -ForegroundColor Green")
        script_content.append("        }")
        script_content.append("        Pop-Location")
        script_content.append("    } else {")
        script_content.append(f"        Write-Host \"[SKIP] No update_prices.py found in {folder}\" -ForegroundColor Yellow")
        script_content.append("    }")
        script_content.append("} else {")
        script_content.append(f"    Write-Host \"[WARNING] Folder does not exist: {folder}\" -ForegroundColor Yellow")
        script_content.append("}")
        script_content.append("")
    
    script_content.append("Write-Host \"\"")
    script_content.append("Write-Host \"=\" * 60")
    script_content.append("Write-Host \"All updates completed!\"")
    script_content.append("Write-Host \"=\" * 60")
    
    # Write the script
    output_script = SCRIPT_DIR / "run_updates.ps1"
    with open(output_script, 'w', encoding='utf-8') as f:
        f.write('\n'.join(script_content))
    
    print(f"✅ Generated PowerShell script: {output_script}")
    print(f"   Configured {len(FOLDERS)} folder(s):")
    for folder in FOLDERS:
        print(f"     - {folder}")
    print(f"\nTo run the script, execute:")
    print(f"   .\\Crypto\\update\\run_updates.ps1")


if __name__ == "__main__":
    generate_powershell_script()

